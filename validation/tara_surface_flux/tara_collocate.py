#!/usr/bin/env python
"""
Tara 2007 broadband albedo vs CLARA-A3 and APP-x.
Input: tara_broadband_daily.csv, generated by prepare_tara_broadband.py
from Aku Riihela's supplied radiometer workbook and drift coordinates.
Daily albedo is the ratio of accepted summed reflected/incoming SW flux.
See tara_broadband_processing.json for filtering and timestamp assumptions.
Satellite sampling and SIC blending retain the existing validation method.
"""
import glob
import os
import re

import numpy as np
import pandas as pd
import xarray as xr
from pyproj import Transformer

TARA = "/glade/work/jrotondo/albedo_satellite_validation/tara_surface_flux"
DIR_SIAL = "/glade/derecho/scratch/jrotondo/clara_a3_obs"
DIR_APPX = "/glade/derecho/scratch/jrotondo/APP-x_observations"
DIR_SIC = "/glade/derecho/scratch/jrotondo/SIC_data"

ALPHA_WATER = 0.06
ROTATION_ANGLE = -45.0
PENTAD_DAYS = 5


def rotate(x, y, deg):
    a = np.deg2rad(deg)
    return x * np.cos(a) - y * np.sin(a), x * np.sin(a) + y * np.cos(a)


# ---------------------------------------------------------------- in situ
t = pd.read_csv(f"{TARA}/tara_broadband_daily.csv", parse_dates=["date"])
t = t[["date", "alb", "n", "lat", "lon"]].dropna(subset=["alb"]).reset_index(drop=True)
print(f"Tara in-situ days (broadband albedo): {len(t)}  "
      f"{t.date.min().date()} -> {t.date.max().date()}")
print(f"  lat {t.lat.min():.2f}-{t.lat.max():.2f}  alb {t.alb.min():.3f}-{t.alb.max():.3f}")

tf = Transformer.from_crs("EPSG:4326", "EPSG:3413", always_xy=True)
t["x"], t["y"] = tf.transform(t.lon.values, t.lat.values)

# SIC from the NSIDC PSN25 field (the Tara file carries none)
fsic = []
for _, r in t.iterrows():
    g = sorted(glob.glob(f"{DIR_SIC}/sic_psn25_{r.date.strftime('%Y%m%d')}_*.nc"))
    if not g:
        fsic.append(np.nan)
        continue
    ds = xr.open_dataset(g[0])
    name = next((v for v in ds.data_vars if "sic" in v.lower()
                 or "concentration" in v.lower()), None)
    if name is None:
        ds.close()
        fsic.append(np.nan)
        continue
    sx, sy = rotate(r.x, r.y, ROTATION_ANGLE)
    v = ds[name]
    v = v.isel({d: 0 for d in v.dims if d not in ("x", "y")}) if v.ndim > 2 else v
    try:
        a = float(v.interp(x=sx, y=sy, method="linear").values)
    except Exception:
        a = np.nan
    ds.close()
    if a > 1.5:          # stored as percent
        a = a / 100.0
    fsic.append(np.clip(a, 0.0, 1.0) if np.isfinite(a) else np.nan)

t["fsic"] = fsic
print(f"  SIC retrieved for {t.fsic.notna().sum()} of {len(t)} days, "
      f"mean {t.fsic.mean()*100:.1f}%")
t["fsic_assumed"] = t.fsic.isna()
if t.fsic_assumed.any():
    print(f"  NOTE: {t.fsic_assumed.sum()} days use the existing 100% SIC fallback.")
t["fsic"] = t.fsic.fillna(1.0)          # Riihela: SIC at the sensors was 100%
t["alb_blend"] = t.fsic * t.alb + (1.0 - t.fsic) * ALPHA_WATER


# ---------------------------------------------------------------- CLARA-A3
rows = []
for f in sorted(glob.glob(f"{DIR_SIAL}/SALpm2007*.nc")):
    m = re.search(r"SALpm(\d{8})", os.path.basename(f))
    t0 = pd.Timestamp(m.group(1))
    t1 = t0 + pd.Timedelta(days=PENTAD_DAYS)
    sub = t[(t.date >= t0) & (t.date < t1)]
    if len(sub) == 0:
        continue
    ds = xr.open_dataset(f)
    xm, ym = float(sub.x.mean()), float(sub.y.mean())
    try:
        sat = float(ds.blue_sky_albedo_all_mean.isel(time=0)
                    .interp(x=xm, y=ym, method="linear").values) / 100.0
        sza = float(ds.sun_zenith_angle_mean.isel(time=0)
                    .interp(x=xm, y=ym, method="linear").values)
    except Exception:
        ds.close()
        continue
    ds.close()
    if not np.isfinite(sat) or sat <= 0 or sat > 1.05:
        continue
    rows.append(dict(pentad=t0, n_days=len(sub), lat=sub.lat.mean(), lon=sub.lon.mean(),
                     insitu=sub.alb_blend.mean(), insitu_raw=sub.alb.mean(),
                     fsic=sub.fsic.mean(), sat=sat, sza=sza))

cl = pd.DataFrame(rows, columns=["pentad", "n_days", "lat", "lon", "insitu", "insitu_raw", "fsic", "sat", "sza"])
print(f"\nCLARA-A3 pentad matchups: {len(cl)}")


# ---------------------------------------------------------------- APP-x
rows = []
for _, r in t.iterrows():
    cand = sorted(glob.glob(f"{DIR_APPX}/{r.date.year}/*_d{r.date.strftime('%Y%m%d')}_*.nc"))
    if not cand:
        continue
    vals = []
    for f in cand:
        ds = xr.open_dataset(f)
        v = ds.get("cdr_surface_albedo")
        if v is None:
            ds.close()
            continue
        v = v.isel(Time=0) if "Time" in v.dims else v
        la, lo = ds.latitude.values, ds.longitude.values
        dist = (np.radians(la - r.lat) ** 2
                + (np.radians(lo - r.lon) * np.cos(np.radians(r.lat))) ** 2)
        j, k = np.unravel_index(np.nanargmin(dist), dist.shape)
        a = float(np.asarray(v)[j, k])
        ds.close()
        if np.isfinite(a) and 0 < a <= 1.05:
            vals.append(a)
    if vals:
        rows.append(dict(date=r.date, lat=r.lat, lon=r.lon, insitu=r.alb_blend,
                         insitu_raw=r.alb, fsic=r.fsic,
                         sat=float(np.mean(vals)), n_ov=len(vals)))

ax = pd.DataFrame(rows, columns=["date", "lat", "lon", "insitu", "insitu_raw", "fsic", "sat", "n_ov"])
print(f"APP-x daily matchups: {len(ax)}")


# ---------------------------------------------------------------- stats
def stats(df, label):
    if len(df) < 3:
        print(f"{label}: too few matchups ({len(df)})")
        return None
    b = df.sat - df.insitu
    out = dict(platform="Tara 2007 (broadband albedo)", product=label, n=len(df),
               insitu_mean=df.insitu.mean(), sat_mean=df.sat.mean(),
               bias=b.mean(), mean_abs_diff=b.abs().mean(),
               rmse=float(np.sqrt((b ** 2).mean())),
               r=np.corrcoef(df.insitu, df.sat)[0, 1],
               insitu_sd=df.insitu.std(), sat_sd=df.sat.std(),
               albedo_type="broadband")
    print(f"\n{label}:  n={out['n']}  in-situ {out['insitu_mean']:.3f}  sat {out['sat_mean']:.3f}")
    print(f"   bias {out['bias']:+.3f}   mean|diff| {out['mean_abs_diff']:.3f}   "
          f"RMSE {out['rmse']:.3f}   r {out['r']:+.3f}")
    return out


res = [x for x in (stats(cl, "CLARA-A3"), stats(ax, "APP-x")) if x]
cl["albedo_type"] = "broadband"
ax["albedo_type"] = "broadband"
cl.to_csv(f"{TARA}/tara_broadband_clara_matchups.csv", index=False)
ax.to_csv(f"{TARA}/tara_broadband_appx_matchups.csv", index=False)
pd.DataFrame(res).to_csv(f"{TARA}/tara_broadband_validation_stats.csv", index=False)
print(f"\nwrote matchup tables and stats to {TARA}")

# Riihela window, for direct comparison with the published broadband numbers
if len(cl):
    w = cl[(cl.pentad >= "2007-06-01") & (cl.pentad < "2007-09-01")]
    if len(w) >= 3:
        b = w.sat - w.insitu
        print(f"\nRiihela 2010 window (1 Jun - 31 Aug 2007), CLARA-A3, pentads:")
        print(f"   n={len(w)}  in-situ {w.insitu.mean():.3f}  sat {w.sat.mean():.3f}  "
              f"bias {b.mean():+.3f}  RMSE {np.sqrt((b**2).mean()):.3f}")
        print(f"   published broadband: Tara 0.578, SAL 0.552, RMSE 0.069, n=39")
